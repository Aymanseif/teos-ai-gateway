/**
 * Generates components/QrCode.jsx (inline SVG) for the release SHA-256 and
 * PROVES the QR is correct by decoding a rendered PNG back to the payload.
 *
 *   npm run generate:qr
 */
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import { PNG } from 'pngjs';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const PAYLOAD = 'SHA256:AAD854983D7A1A1A1B2E330B24EC5A86C73660CCB38E52513FB2055065450056';

const here = dirname(fileURLToPath(import.meta.url));

// 1. Render an opaque PNG and decode it back — a real round-trip check.
const pngBuf = await QRCode.toBuffer(PAYLOAD, {
  type: 'png',
  margin: 2,
  scale: 8,
  errorCorrectionLevel: 'M',
  color: { dark: '#050505ff', light: '#ffffffff' },
});
const png = PNG.sync.read(pngBuf);
const decoded = jsQR(new Uint8ClampedArray(png.data), png.width, png.height);

if (!decoded || decoded.data !== PAYLOAD) {
  console.error(
    JSON.stringify({
      ok: false,
      reason: 'decode_mismatch',
      expected: PAYLOAD,
      got: decoded ? decoded.data : null,
    }),
  );
  process.exit(1);
}

// 2. Emit a transparent-background SVG so it can sit on the parchment mat.
const svg = await QRCode.toString(PAYLOAD, {
  type: 'svg',
  margin: 1,
  errorCorrectionLevel: 'M',
  color: { dark: '#050505', light: '#00000000' },
});

const responsive = svg.replace(
  '<svg ',
  '<svg style="width:100%;height:auto;display:block" ',
);

const file = `// AUTO-GENERATED by \`npm run generate:qr\` — do not edit by hand.
export const QR_PAYLOAD = ${JSON.stringify(PAYLOAD)};

export default function QrCode({ className = '' }) {
  return (
    <div
      className={className}
      role="img"
      aria-label={'QR code encoding ' + QR_PAYLOAD}
      dangerouslySetInnerHTML={{ __html: ${JSON.stringify(responsive)} }}
    />
  );
}
`;

writeFileSync(join(here, '..', 'components', 'QrCode.jsx'), file, 'utf8');

console.log(
  JSON.stringify({
    ok: true,
    payload: PAYLOAD,
    decoded: decoded.data,
    match: decoded.data === PAYLOAD,
    modules: Math.round(png.width / 8) - 4,
    png: `${png.width}x${png.height}`,
  }),
);
